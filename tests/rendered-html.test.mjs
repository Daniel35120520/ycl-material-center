import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";

test("builds the YCL shell and D1 authentication routes", async () => {
  const page = await readFile(new URL("../app/page.tsx", import.meta.url), "utf8");
  const portal = await readFile(new URL("../app/auth-portal.tsx", import.meta.url), "utf8");
  const loginRoute = await readFile(new URL("../app/api/auth/login/route.ts", import.meta.url), "utf8");
  const pairsRoute = await readFile(new URL("../app/api/pairs/route.ts", import.meta.url), "utf8");
  const projectsRoute = await readFile(new URL("../app/api/projects/route.ts", import.meta.url), "utf8");
  const worker = await readFile(new URL("../dist/server/index.js", import.meta.url), "utf8");
  assert.match(page, /材料研發中心/);
  assert.match(page, /資料填寫/);
  assert.match(page, /SPC 分析/);
  assert.match(portal, /帳密登入/);
  assert.match(portal, /申請帳號/);
  assert.match(portal, /帳號申請與啟用/);
  assert.match(loginRoute, /PENDING_ACTIVATION/);
  assert.match(pairsRoute, /export async function POST/);
  assert.match(pairsRoute, /export async function DELETE/);
  assert.match(projectsRoute, /export async function DELETE/);
  assert.match(projectsRoute, /此大專案已有正式資料/);
  assert.match(page, /deleteProject/);
  assert.match(page, /deleteBranch/);
  assert.match(page, /defaultMachineTypes/);
  assert.match(page, /攪拌棒/);
  assert.match(page, /自訂類別（選填）/);
  assert.match(page, /item\.ingredients\.length===0/);
  assert.match(page, /template\.map\(ingredient=>\(\{\.\.\.ingredient\}\)\)/);
  assert.match(page, /標準品檢驗（選填）/);
  assert.match(page, /result\.available===false/);
  assert.match(page, /outOfSpecMetrics/);
  assert.match(page, /各專案 USL／LSL/);
  assert.match(page, /X 軸主分組（顏色）/);
  assert.match(page, /次分組（形狀）/);
  assert.match(page, /processRpm/);
  assert.match(page, /machine:\$\{string\}/);
  assert.match(page, /projectMachineTypes/);
  assert.match(page, /machineTypes\.map/);
  assert.match(page, /EditableDoeDetails/);
  assert.match(page, /設定溫度（°C）/);
  assert.match(page, /實際內溫（°C）/);
  assert.match(page, /新增一段製程/);
  assert.match(page, /USL／LSL 為深橘色虛線/);
  assert.match(page, /point\.value\.toFixed\(2\)/);
  assert.match(page, /SparkChart points=\{points\}/);
  assert.match(pairsRoute, /d\.process_json AS doeProcess/);
  assert.match(pairsRoute, /machines_json = \?, process_json = \?/);
  assert.match(pairsRoute, /__MISSING_STANDARD__/);
  assert.doesNotMatch(page, /標準品批次"><input required/);
  assert.doesNotMatch(page, /ACP-DOE-02[1-6]|ACP-STD-02[1-6]|PEDOT:PSS|MX-01|ACP 導電膠開發|銀膠材料開發|高銀含量配方|低黏度配方/);
  assert.ok(worker.length > 1000);
  assert.doesNotMatch(page + portal, /codex-preview|react-loading-skeleton/i);
});
